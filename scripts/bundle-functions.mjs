import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const fnDir = path.join(root, 'supabase/functions');
const slugs = ['sync-catalogue', 'ingest-market-data', 'ingest-brief', 'ingest-heartbeat', 'run-daily-cycle', 'admin-sync'];

const denoNpm = {
  name: 'deno-npm',
  setup(b) {
    b.onResolve({ filter: /^@supabase\/supabase-js$/ }, () => ({ path: 'npm:@supabase/supabase-js@2.57.4', external: true }));
  },
};

for (const slug of slugs) {
  await build({
    entryPoints: [path.join(fnDir, '_shared/server/endpoints', `${slug}.ts`)],
    outfile: path.join(fnDir, slug, 'index.ts'),
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    minify: true,
    plugins: [denoNpm],
    banner: { js: '// @ts-nocheck\n// Generated by scripts/bundle-functions.mjs from supabase/functions/_shared/server. Do not edit by hand.' },
    logLevel: 'warning',
  });
}
console.log(`Bundled ${slugs.length} functions.`);
